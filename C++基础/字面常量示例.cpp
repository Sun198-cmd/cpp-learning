#include <iostream>
using namespace std;
int main()
{
    //整型，实型，字符，字符串
    //整形（整数）
    21;

    //实型（小数）
    180.5;

    //字符，' '进行包围，单个字符
    'c';         //只能提供1个字符

    //字符串，“”进行包围，任意个字符
    "";         //空字符串是可行的
    "c";        //标准的字符串
    "sxc";      //标准的字符串

    //通过cout输出到控制台上
    cout<<21<<endl;
    cout<<180.5<<endl;
    cout<<'c'<<endl;
    cout<<"sxc"<<endl;
    return 0;

}